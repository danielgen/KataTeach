#!/usr/bin/env python3
"""Quarantine derived results below the explicitly named legacy ``games/old gs`` tree.

Only ``snorkel.jsonl`` and ``viz.html`` are moved. Raw moves, SGFs, metadata,
and trunk activations remain in place. The fixed source root and fixed filename
allowlist make the operation deliberately non-generic and auditable.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil


ARCHIVE_ID = "20260730_nested_old_gs_invalid_v1"
DERIVED_NAMES = frozenset({"snorkel.jsonl", "viz.html"})
REASON_CODES = (
    "MOVE_LOC_PADDED_AS_FLAT",
    "LABEL_READOUT_MISMATCH",
    "NON_NESTED_CV",
    "IN_SAMPLE_CAUSAL",
    "CONTROLS_NOT_POLICY_MATCHED",
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    repo = Path(__file__).resolve().parents[1]
    source_root = (repo / "games" / "old gs").resolve()
    expected_root = (repo / "games" / "old gs").resolve()
    if source_root != expected_root or not source_root.is_dir():
        raise FileNotFoundError(f"Fixed legacy source root is absent: {source_root}")
    archive = repo / "daniele_experiment" / "artifacts" / "archive" / ARCHIVE_ID
    if archive.exists():
        raise FileExistsError(f"Refusing to reuse archive: {archive}")

    targets = sorted(
        path
        for path in source_root.rglob("*")
        if path.is_file() and path.name in DERIVED_NAMES
    )
    if not targets:
        raise FileNotFoundError("No allowlisted nested legacy results remain")
    entries = []
    for source in targets:
        relative = source.relative_to(repo)
        archived_path = Path("files") / relative
        entries.append(
            {
                "original_path": str(relative),
                "archived_path": str(archived_path),
                "bytes": int(source.stat().st_size),
                "sha256": _sha256(source),
                "reason_codes": list(REASON_CODES),
            }
        )

    archive.mkdir(parents=True)
    for source, entry in zip(targets, entries):
        destination = archive / entry["archived_path"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(source), str(destination))

    manifest = {
        "schema_version": 1,
        "archive_id": ARCHIVE_ID,
        "status": "invalid_do_not_use",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_root": str(source_root.relative_to(repo)),
        "allowlisted_derived_names": sorted(DERIVED_NAMES),
        "reason_codes": list(REASON_CODES),
        "reason": (
            "Nested legacy labels and visualizations were generated by the same "
            "pre-correction workflow as the primary invalid result set. They are "
            "preserved for audit only and excluded from all validated analysis."
        ),
        "raw_files_moved": False,
        "file_count": len(entries),
        "total_bytes": sum(entry["bytes"] for entry in entries),
        "files": entries,
    }
    (archive / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (archive / "checksums.sha256").write_text(
        "".join(
            f"{entry['sha256']}  {entry['archived_path']}\n" for entry in entries
        )
    )
    (archive / "INVALID.md").write_text(
        "# Invalid nested legacy results — do not use\n\n"
        "Status: `invalid_do_not_use`\n\n"
        "Only derived `snorkel.jsonl` and `viz.html` files were moved. Raw moves, "
        "SGFs, metadata, and trunk activations remain in `games/old gs`.\n"
    )
    print(
        json.dumps(
            {
                "archive": str(archive),
                "files": len(entries),
                "bytes": manifest["total_bytes"],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
